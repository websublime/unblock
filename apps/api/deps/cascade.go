// cascade.go declares the two Pub/Sub topic payload types and the
// pubsub.NewTopic registrations for the deps cascade subsystem.
//
// SPEC anchors:
//
//   - §6.3.1 — locked shape of CascadeRequested and CascadeCompleted,
//     including the TraceID field on CascadeRequested (ULID minted
//     by the mcp raw endpoint, copied from ctx into the payload at
//     publish time because Encore Pub/Sub does not propagate
//     context.Context across the topic boundary; SPEC §10.2 Option B).
//   - §6.3.2 — subscriber contract. The subscriber itself lands in
//     bead unblock-tv8.12 (C-3); A-5 only lands the types and topic
//     declarations so downstream consumers (workitems.Close,
//     deps.AddEdge, the C-3 handler) can populate / read TraceID
//     from day one without re-shaping the surface later.
//   - §8.3 — cascade_events row writer (also C-3 / Tool 12).
//
// DEVIATION from §6.3.1 literal: the spec example writes the topic
// name as "deps.cascade.requested" (dot-separated) but Encore
// v1.52.1 enforces kebab-case on pubsub topic names (parser error
// E1186). We use "deps-cascade-requested" / "deps-cascade-completed"
// — same semantic identifier, different separator. Tracked on the
// A-5 implementation bead.
//
// Why TraceID rides on the payload (not on ctx alone): the SPEC's
// §10.2 round-5 lock keeps trace_id on context.Context across
// in-process and Encore-generated-client RPC boundaries (Encore
// carries ctx for free), but Pub/Sub explicitly serialises the
// message to a queue and the subscriber's ctx is a fresh one
// minted by the runtime — context.Value bindings do not survive
// the topic boundary. The publisher therefore copies TraceID from
// tracectx.From(ctx) into CascadeRequested at publish time and
// the subscriber writes it back to deps.cascade_events.trace_id.

package deps

import (
	"time"

	"encore.dev/pubsub"
)

// CascadeRequested is the Pub/Sub payload published by the deps and
// workitems services when an item's readiness state may have changed
// (close, edge added, edge removed, state change). Subscribers fan
// out the affected closure and recompute is_ready / pipeline_stage
// per §6.3.2.
//
// EventID is generated by the publisher (a ULID) and used by the
// subscriber's idempotency clause:
// `INSERT ... ON CONFLICT (event_id, triggered_by_item_id) DO NOTHING`
// per AR-11.
type CascadeRequested struct {
	// EventID is a ULID minted by the publisher. The subscriber
	// uses (EventID, TriggeredByItemID) as the idempotency key
	// (UNIQUE constraint on deps.cascade_events).
	EventID string `json:"event_id"`

	// OrgID, ProjectID scope the cascade to the org-tenant that
	// triggered it.
	OrgID     string `json:"org_id"`
	ProjectID string `json:"project_id"`

	// TriggeredByItemID is the item whose change initiated the
	// cascade (e.g. the item being closed in workitems.Close).
	TriggeredByItemID string `json:"triggered_by_item_id"`

	// Reason categorises the trigger. Allowed: "close" |
	// "edge_added" | "edge_removed" | "state_change".
	//
	// Round-6 cascade-symmetry (SPEC §6.3.0 — 2026-05-12) ships
	// all four kinds through the symmetric writer model:
	//
	//   - "close":        workitems.Close (Tool 6) post-commit.
	//   - "edge_added":   deps.AddEdge (Tool 11 / §6.5) post-commit.
	//   - "edge_removed": deps.RemoveEdge (Tool 12) post-commit,
	//                     REUSING the event_id captured before BEGIN
	//                     for the inline audit row — the subscriber's
	//                     ON CONFLICT (event_id, triggered_by_item_id)
	//                     DO NOTHING collapses to no-op (exactly one
	//                     audit row per logical remove). The
	//                     subscriber's pipeline_stage recompute pass
	//                     still runs.
	//   - "state_change": workitems.SetStateColumns (Tool 13) on
	//                     §5.7.1-affecting writes, plus workitems.Claim
	//                     on the I-3 reset path only.
	//
	// Regime split (SPEC §6.3.0): is_ready is single-hop and writer-
	// inline (Regime A); pipeline_stage is multi-hop and subscriber-
	// only (Regime B). The subscriber MUST NOT write is_ready for any
	// Reason value — that invariant is enforced by
	// shared/lint/no_direct_is_ready_write with a scope-tightened
	// allow-list (encore.app/deps writes is_ready inline; subscriber
	// in the same package writes pipeline_stage only).
	Reason string `json:"reason"`

	// TraceID is the ULID minted by the mcp raw endpoint
	// (§10.2 Option B). The publisher copies it from
	// tracectx.From(ctx) into the payload at publish time —
	// Encore Pub/Sub does not propagate context.Context across
	// the topic boundary, so the subscriber would otherwise lose
	// the audit/business correlation id. The subscriber writes
	// this value back to deps.cascade_events.trace_id per §8.3
	// (the column is `text` and accepts the ULID verbatim).
	//
	// Empty string is permitted (some non-MCP code paths may
	// publish cascades — e.g. an admin script — without an
	// originating MCP request; the subscriber tolerates a
	// missing trace id by writing NULL to the column).
	TraceID string `json:"trace_id"`

	// EmittedAt is the publisher's wall clock at publish time.
	// Distinct from Encore Pub/Sub's own delivery timestamps so
	// the audit row can record "when did the cascade start in
	// the publisher's view".
	EmittedAt time.Time `json:"emitted_at"`
}

// CascadeCompleted is the Pub/Sub payload published by the cascade
// subscriber after a successful pass. P01 surfaces it for downstream
// observers (currently none); the subscriber's DB commit on
// deps.cascade_events is the source-of-truth audit row, so this
// topic is best-effort.
//
// TraceID is intentionally absent: subscribers that want trace
// correlation should join on EventID against deps.cascade_events
// (which carries trace_id per §8.3). Adding TraceID to this payload
// would duplicate the audit row's column without adding new
// information.
type CascadeCompleted struct {
	// EventID matches the EventID of the CascadeRequested that
	// triggered this completion.
	EventID string `json:"event_id"`

	// TriggeredByItemID matches the originating
	// CascadeRequested.TriggeredByItemID.
	TriggeredByItemID string `json:"triggered_by_item_id"`

	// AffectedItemIDs is the closure of items whose is_ready /
	// pipeline_stage was recomputed by this pass. May be empty
	// if no readiness flip occurred (the subscriber still emits
	// CascadeCompleted for the audit-trail completeness).
	AffectedItemIDs []string `json:"affected_item_ids"`

	// CascadedCount is len(AffectedItemIDs); duplicated on the
	// wire so simple consumers don't have to walk the slice.
	CascadedCount int `json:"cascaded_count"`

	// CompletedAt is the subscriber's wall clock at commit time.
	CompletedAt time.Time `json:"completed_at"`
}

// CascadeRequestedTopic is the Pub/Sub topic carrying
// CascadeRequested events. The C-3 subscriber (bead unblock-tv8.12)
// will register against this topic via pubsub.NewSubscription per
// SPEC §6.3.2.
//
// DeliveryGuarantee: AtLeastOnce. Idempotency is guaranteed by the
// (event_id, triggered_by_item_id) UNIQUE constraint on
// deps.cascade_events plus the subscriber's
// `ON CONFLICT ... DO NOTHING` clause — duplicate deliveries
// degrade to no-op inserts (AR-11).
//
//nolint:gochecknoglobals // pubsub topics are package-level by Encore contract.
var CascadeRequestedTopic = pubsub.NewTopic[*CascadeRequested]("deps-cascade-requested",
	pubsub.TopicConfig{DeliveryGuarantee: pubsub.AtLeastOnce})

// CascadeCompletedTopic is the Pub/Sub topic carrying
// CascadeCompleted events. P01 has no subscriber; the topic ships
// to lock the surface for downstream phases (observability
// consumers, e.g. a "cascade fan-out latency" metric collector).
//
//nolint:gochecknoglobals // pubsub topics are package-level by Encore contract.
var CascadeCompletedTopic = pubsub.NewTopic[*CascadeCompleted]("deps-cascade-completed",
	pubsub.TopicConfig{DeliveryGuarantee: pubsub.AtLeastOnce})
